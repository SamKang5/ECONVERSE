    const lessonTitle='Motion reviewed lesson '+config.suffix;
    const fields={'Episode code':'M1','Lesson title':lessonTitle,'Duration':'02 phút','Module ID':'motion-review','Module title':'Motion review','Unit code':'motion','YouTube video URL':'https://www.youtube.com/watch?v=fO4tKHj3_lA','Module description':'Local motion QA','Short description':'Local motion acceptance','Overview':'Review feedback and publication.','Content heading':'Motion acceptance','Content paragraphs · one paragraph per line':'This local lesson is an acceptance fixture.','Learning objectives · one per line':'Verify publication feedback.'};
    for(const [label,value] of Object.entries(fields))await page.getByLabel(label,{exact:true}).fill(value);
    await page.getByRole('button',{name:'Add question',exact:true}).click();
    await page.getByLabel('Question 1 text',{exact:true}).fill('Who publishes lessons?');
    for(const [i,letter] of ['A','B','C','D'].entries())await page.getByLabel('Question 1 option '+letter,{exact:true}).fill(['Admin','Learner','Guest','Nobody'][i]);
    await page.getByLabel('Question 1 explanation',{exact:true}).fill('An admin reviews before publishing.');
    await page.getByRole('button',{name:'Save draft',exact:true}).click();
    await page.locator('.mg-save-state').filter({hasText:'All changes saved.'}).waitFor();
    verify(true,'Saved status follows confirmed draft persistence');
    await page.getByRole('button',{name:'Submit for review',exact:true}).click();
    await page.getByRole('status').filter({hasText:'Draft submitted for review.'}).waitFor();
    await logout('Đăng xuất');await login(config.accounts.admin);
    await nav('Admin Console');await page.getByRole('button',{name:'Review queue',exact:true}).click();
