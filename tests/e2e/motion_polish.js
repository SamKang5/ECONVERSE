    await page.getByRole('button',{name:'Publish lesson',exact:true}).click();
    await page.getByRole('status').filter({hasText:'Lesson published.'}).waitFor();
    const unpublish=page.getByRole('button',{name:'Unpublish lesson',exact:true});
    let decisions=0;
    page.on('request',request=>{if(request.method()==='POST'&&request.url().includes('/api/admin/revisions/')&&request.url().endsWith('/unpublish'))decisions++;});
    await unpublish.click();await page.getByRole('dialog',{name:'Unpublish this lesson?',exact:true}).waitFor();
    await scan('unpublish confirmation');await shot('after-confirmation');
    await page.keyboard.press('Escape');await page.getByRole('dialog').waitFor({state:'hidden'});
    verify(decisions===0,'Cancelling confirmation makes no publication request');
    verify(await unpublish.evaluate(e=>e===document.activeElement),'Confirmation cancellation restores original focus');
    await unpublish.click();
    await page.route('**/api/admin/revisions/*/unpublish',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:{code:'UNAVAILABLE',message:'Motion QA: retry unpublish'}})}));
    await page.getByRole('button',{name:'Confirm unpublish',exact:true}).click();
    await page.getByRole('dialog').getByRole('alert').waitFor();
    verify(await page.getByRole('dialog').isVisible(),'Failed confirmation exposes its error inside the modal');
