    verify(await video.evaluate(e=>e.isConnected),'Lesson iframe survives quiz entry');
    await page.getByRole('button',{name:'Bài học',exact:true}).click();
    verify(await video.evaluate(e=>e.isConnected),'Returning from quiz retains original iframe');
    await page.getByRole('button',{name:'Làm bài kiểm tra',exact:true}).click();
    await page.getByRole('button',{name:'Nộp bài kiểm tra',exact:true}).click();
