    await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
    verify(await opener.evaluate(e=>e===document.activeElement),'Escape restores auth opener focus');
    await opener.click();await dialog.getByRole('button',{name:'Đăng ký',exact:true}).click();
    const learner={email:'motion-'+config.suffix+'@review.invalid',password:config.suffix+'Motion-aA1!',displayName:'Motion Learner'};
    await dialog.getByLabel('Tên hiển thị').fill(learner.displayName);
    await dialog.getByLabel('Địa chỉ email').fill(learner.email);
    await dialog.getByLabel('Mật khẩu').fill(learner.password);
    await dialog.getByRole('button',{name:'Tạo tài khoản & Bắt đầu học',exact:true}).click();await dialog.waitFor({state:'hidden'});
    await page.getByRole('button',{name:'Hồ sơ Motion Learner',exact:true}).waitFor();
    await nav('Thư viện bài học');await page.locator('.module-heading').first().waitFor();
    verify(await page.locator('main').evaluate(e=>e===document.activeElement),'Navigation focuses the main region');
    const module=page.locator('.course-module').first(),toggle=module.locator('.module-heading');
    await toggle.click();
    verify(await toggle.getAttribute('aria-expanded')==='false','Course collapse exposes expanded state');
    verify(await module.locator('.motion-collapse').evaluate(e=>e.inert),'Collapsed course lessons leave keyboard navigation');
    await toggle.click();await module.locator('.library-lesson').first().waitFor({state:'visible'});
    await page.getByRole('button',{name:'Tài chính',exact:true}).click();
    await page.getByRole('textbox',{name:'Tìm bài học'}).fill('Lập ngân sách');
    verify(await page.locator('.library-lesson').count()===1,'Category and search still filter lessons');
    await page.getByRole('button',{name:'Tất cả',exact:true}).click();
    await page.getByRole('textbox',{name:'Tìm bài học'}).fill('Độ co giãn của cầu theo giá');
    await scan('filtered library');await page.locator('.library-lesson').first().click();
