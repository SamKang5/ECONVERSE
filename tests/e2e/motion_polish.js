    const opener=page.getByRole('button',{name:'Đăng nhập',exact:true});
    await opener.click();
    const dialog=page.getByRole('dialog');
    await scan('auth dialog');
    await dialog.getByRole('button',{name:'Đăng nhập ngay',exact:true}).focus();await page.keyboard.press('Tab');
