    await shot('after-quiz-selected');await scan('answered quiz');
    const keys=[];
    let release,arrived;
    const gate=new Promise(resolve=>release=resolve),intercepted=new Promise(resolve=>arrived=resolve);
    await page.route('**/api/quizzes/lesson-2a/submit',async route=>{keys.push(route.request().postDataJSON().idempotencyKey);arrived();await gate;await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:{code:'UNAVAILABLE',message:'Motion QA: retry submission'}})});});
    await page.getByRole('button',{name:'Nộp bài kiểm tra',exact:true}).click();await intercepted;
    verify(await page.getByRole('button',{name:'Đang nộp bài…',exact:true}).isDisabled(),'Pending submission disables duplicate submit');
    verify(await page.locator('.xp-reward,.quiz-result').count()===0,'No reward or result before backend response');
    release();await page.getByRole('alert').waitFor();
    verify(await page.locator('.xp-reward').count()===0,'Failed submission never celebrates XP');
    await page.unroute('**/api/quizzes/lesson-2a/submit');
    page.on('request',request=>{if(request.url().endsWith('/api/quizzes/lesson-2a/submit'))keys.push(request.postDataJSON().idempotencyKey);});
    await page.getByRole('button',{name:'Nộp bài kiểm tra',exact:true}).click();await page.locator('.quiz-result').waitFor();
    verify(keys[0]===keys[1],'Network retry preserves quiz idempotency key');
    verify(await page.locator('.xp-reward').count()===0,'Incorrect backend grade never celebrates XP');
    verify(await page.locator('.quiz-option.wrong').count()===4,'Wrong answers receive explicit feedback');
    await page.getByRole('button',{name:'Làm lại',exact:true}).click();
    await page.getByRole('button',{name:'Nộp bài kiểm tra',exact:true}).waitFor();
    for(let i=0;i<config.answers.length;i++)await page.locator('.quiz-question').nth(i).getByRole('radio').nth(config.answers[i]).check();
    await page.getByRole('button',{name:'Nộp bài kiểm tra',exact:true}).click();
    await page.getByRole('heading',{name:'100% · 4/4 câu đúng',exact:true}).waitFor();
    verify(await page.locator('.xp-reward').innerText()==='+45 XP','Confirmed success reveals exactly the backend XP award');
    verify(await page.locator('.quiz-result').evaluate(e=>e===document.activeElement),'Quiz result receives keyboard focus');
    await scan('confirmed quiz result');await shot('after-quiz-result');
    await page.getByRole('button',{name:'Bài học',exact:true}).click();await page.getByRole('button',{name:'Kiểm tra kiến thức',exact:true}).click();
    verify(await page.locator('.xp-reward.is-celebrating').count()===0,'Revisiting result does not replay celebration');
    await page.getByRole('button',{name:'Làm lại',exact:true}).click();await page.getByRole('button',{name:'Nộp bài kiểm tra',exact:true}).waitFor();
    for(let i=0;i<config.answers.length;i++)await page.locator('.quiz-question').nth(i).getByRole('radio').nth(config.answers[i]).check();
    await page.getByRole('button',{name:'Nộp bài kiểm tra',exact:true}).click();await page.locator('.quiz-result').waitFor();
    verify(await page.locator('.xp-reward').count()===0,'Repeated perfect completion awards no duplicate XP celebration');
    await page.reload();await ready();await page.locator('.completed-label').waitFor();
    await nav('Hồ sơ của tôi');await page.locator('.xp-history li').first().waitFor();
    verify((await page.locator('.xp-history').innerText()).includes('+45 XP'),'Confirmed XP persists in learner ledger');
    await scan('profile');
    for(const width of [320,390,768,1440]) {
      await page.setViewportSize({width,height:width<500?844:1000});await page.goto(config.base+'/#dashboard');await ready();
      verify(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),width+'px dashboard has no horizontal overflow');
      if(width===390) {
        await shot('after-dashboard-mobile');await page.getByRole('button',{name:'Mở menu',exact:true}).click();
        verify(await page.locator('.workspace').evaluate(e=>e.inert),'Mobile drawer makes workspace inert');
        await scan('mobile navigation');await page.keyboard.press('Escape');
        verify(await page.getByRole('button',{name:'Mở menu',exact:true}).evaluate(e=>e===document.activeElement),'Escape returns mobile navigation focus');
        await page.getByRole('button',{name:'Mở menu',exact:true}).click();await page.setViewportSize({width:768,height:1000});
        await page.waitForFunction(()=>document.activeElement===document.querySelector('main'));
        verify(true,'Resizing an open drawer to desktop retains useful focus');
        await page.setViewportSize({width:390,height:844});
        await nav('Thư viện bài học');await scan('mobile library');await shot('after-library-mobile');
      }
    }
    await page.emulateMedia({reducedMotion:'reduce'});await page.reload();await ready();
    await page.waitForFunction(()=>matchMedia('(prefers-reduced-motion: reduce)').matches&&getComputedStyle(document.querySelector('.page-transition')).animationName==='none');
    verify(await page.locator('.page-transition').evaluate(e=>getComputedStyle(e).animationName==='none'),'Reduced motion disables page animation');
    await page.getByRole('button',{name:'Hồ sơ Motion Learner',exact:true}).click();
    await page.getByRole('heading',{name:'Hồ sơ của tôi',exact:true}).waitFor();
    await page.waitForFunction(()=>matchMedia('(prefers-reduced-motion: reduce)').matches&&getComputedStyle(document.querySelector('.page-transition')).animationName==='none');
    verify(await page.locator('.page-transition').evaluate(e=>getComputedStyle(e).animationName==='none'),'Reduced-motion navigation remains immediate');
    await logout('Đăng xuất khỏi tài khoản');await ready();
    await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();await dialog.waitFor();await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
    verify(await page.evaluate(()=>document.getAnimations().filter(a=>a.playState==='running').length===0),'Reduced-motion dialog closes with no running animations');
    await page.emulateMedia({reducedMotion:'no-preference'});
    await login(config.accounts.editor);await nav('Content Studio');
    await page.getByRole('button',{name:'Create lesson',exact:true}).click();
    await page.getByRole('button',{name:'Written lesson',exact:true}).click();
    verify(await page.getByRole('button',{name:'Written lesson',exact:true}).getAttribute('aria-expanded')==='false','Editor sections collapse accessibly');
    await page.getByRole('button',{name:'Written lesson',exact:true}).click();
    await page.getByLabel('Lesson ID',{exact:true}).fill('motion-draft-'+config.suffix);
    verify((await page.locator('.mg-save-state').innerText()).includes('Unsaved changes'),'Editor status reports unsaved edits truthfully');
